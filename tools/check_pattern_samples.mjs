import assert from 'node:assert/strict';
import {uniformPatternSamples} from './pattern_samples.mjs';
const config={cycles:1,frequency:56,seedRms:1e-7},summary={status:'completed-horizon'};
const base=Array.from({length:9},(_,j)=>({time:j/(8*56),eta:[1e-5,-1e-5]}));
const clone=()=>structuredClone(base);
assert.equal(uniformPatternSamples(config,summary,base).frames.length,9);
const endpoint=clone();endpoint.at(-1).time-=Number.EPSILON;
endpoint.push({time:1/56,eta:[1e-5+1e-19,-1e-5]});
const result=uniformPatternSamples(config,summary,endpoint);
assert.equal(result.frames.length,9);assert.equal(endpoint.length,10);assert.equal(result.extraTerminalObservation.rawIndex,9);
const gap=clone();gap.splice(4,1);assert.throws(()=>uniformPatternSamples(config,summary,gap),/scheduled|cadence/);
const missingEnd=clone();missingEnd.pop();assert.throws(()=>uniformPatternSamples(config,summary,missingEnd),/scheduled/);
const extraTwo=structuredClone(endpoint);extraTwo.push(structuredClone(extraTwo.at(-1)));assert.throws(()=>uniformPatternSamples(config,summary,extraTwo),/scheduled/);
const duplicate=clone();duplicate.splice(4,0,structuredClone(duplicate[4]));assert.throws(()=>uniformPatternSamples(config,summary,duplicate));
const actualNext=clone();actualNext.push({time:9/(8*56),eta:[1e-5,-1e-5]});assert.throws(()=>uniformPatternSamples(config,summary,actualNext),/terminal/);
const changed=structuredClone(endpoint);changed.at(-1).eta[0]=2e-5;assert.throws(()=>uniformPatternSamples(config,summary,changed),/roundoff/);
const invalid=structuredClone(endpoint);invalid.at(-1).eta[0]=null;assert.throws(()=>uniformPatternSamples(config,summary,invalid),/finite/);
assert.throws(()=>uniformPatternSamples(config,{status:'partial-wall-budget'},endpoint),/cadence/);
console.log('Pattern sample cadence: regular/roundoff endpoint accepted; missing, interior duplicate, later-time, altered-state, null, wrong-status defects rejected.');
