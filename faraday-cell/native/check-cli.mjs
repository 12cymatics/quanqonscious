const execute=promisify(execFile);
async function runFile(file,args,options={}){
  try{return {status:0,...await execute(file,args,{encoding:'utf8',...options})};}
  catch(error){return {status:Number.isInteger(error.code)?error.code:null,error,stdout:error.stdout??'',stderr:error.stderr??''};}
}
